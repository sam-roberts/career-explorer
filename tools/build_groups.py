"""Build groups.js: all 357 ANZSCO v1.3 unit groups with official data.

Usage:
  python3 -I tools/build_groups.py > groups.js

Inputs (all in tools/):
  jsa_ai_exposure.csv   JSA "Our Gen AI Transition" occupation table (Sept 2025):
                        category, automation + augmentation exposure, entry-level share.
  groups_web.json       From fetch_groups.py + fix_desc.py: JSA full-time median weekly
                        earnings, ABS ANZSCO skill level, licensing flag, description.
  ato_unit_groups.json  ATO Taxation Statistics 2023-24 Table 15B (unit group totals).
"""
import csv, json, os, re

D = os.path.dirname(os.path.abspath(__file__))
rows = list(csv.DictReader(open(os.path.join(D, "jsa_ai_exposure.csv"), encoding="utf-8-sig")))
web = json.load(open(os.path.join(D, "groups_web.json")))
ato = {g["code"]: g for g in json.load(open(os.path.join(D, "ato_unit_groups.json")))}
sm_label = {g["sm"]: g["smLabel"] for g in ato.values()}

def num(v):
    try: return float(v)
    except (TypeError, ValueError): return None

groups = {}
for r in rows:
    c = r["ANZSCO unit code"].strip()
    g = groups.setdefault(c, {"code": c, "title": r["ANZSCO unit title"].strip().replace(" \\ ", "/")})
    if r["Occupation matrix group"] != "All occupations":
        g["cat"] = r["Occupation matrix group"].strip()
    g["aiAuto"] = num(r["Automation exposure score"])
    g["aiAug"] = num(r["Augmentation exposure score"])
    e = num(r["Share of job ads that are entry level (%)"])
    g["entry"] = e

out = []
for c, g in sorted(groups.items()):
    w = web.get(c, {})
    a = ato.get(c)
    desc = w.get("desc") or None
    if desc:
        desc = re.sub(r"[​\s]+", " ", desc).strip()
        first = re.match(r"^(.+?\.)(\s|$)", desc)
        desc = first.group(1) if first else desc
    out.append({
        "code": c, "title": g["title"], "cat": g.get("cat"),
        "sm": c[:2], "smLabel": sm_label.get(c[:2]),
        "aiAuto": g["aiAuto"], "aiAug": g["aiAug"], "entry": g["entry"],
        "jsaWeekly": w.get("jsaWeekly"), "jsaSlug": w.get("jsaSlug"),
        "skill": w.get("levels") or [], "skillEst": bool(w.get("levelEst")), "lic": w.get("lic"),
        "desc": desc,
        "ato": {"sal": round(a["medSal"]), "total": round(a["medTotal"]), "people": a["people"]} if a and a.get("medSal") else None,
    })

missing_sm = sorted({g["sm"] for g in out if not g["smLabel"]})
print("// AUTO-GENERATED by tools/build_groups.py. Do not edit by hand.")
print("// 357 ANZSCO v1.3 unit groups. Sources: JSA Our Gen AI Transition (2025), JSA occupation profiles")
print("// (ABS Employee Earnings and Hours, May 2025), ABS ANZSCO 2022 skill levels, ATO Taxation Statistics 2023-24 Table 15B.")
print("const AIX_SOURCE = 'Jobs and Skills Australia, Our Gen AI Transition (2025)';")
print("const AIX_URL = 'https://www.jobsandskills.gov.au/studies/generative-artificial-intelligence-capacity-study/occupation-data-on-ai-exposure';")
print("const ANZSCO_URL = 'https://www.abs.gov.au/statistics/classifications/anzsco-australian-and-new-zealand-standard-classification-occupations/2022/browse-classification/';")
print("const GROUPS = " + json.dumps(out, separators=(",", ":")) + ";")
if missing_sm:
    import sys; print("missing sub-major labels:", missing_sm, file=sys.stderr)
